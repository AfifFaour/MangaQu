export const getChaptersByMangaId = (mangaId) => {
  return chapterData[mangaId] || [];
};

export const getChapterById = (mangaId, chapterId) => {
  const chapters = chapterData[mangaId];
  return chapters ? chapters.find(chapter => chapter.id === parseInt(chapterId)) : null;
};

export const getLatestChapter = (mangaId) => {
  const chapters = chapterData[mangaId];
  return chapters ? chapters[chapters.length - 1] : null;
};

export const getTotalChapters = (mangaId) => {
  const chapters = chapterData[mangaId];
  return chapters ? chapters.length : 0;
};

export const searchChapters = (mangaId, query) => {
  const chapters = chapterData[mangaId];
  if (!chapters) return [];
  
  const lowerQuery = query.toLowerCase();
  return chapters.filter(chapter =>
    chapter.title.toLowerCase().includes(lowerQuery) ||
    chapter.number.toString().includes(query)
  );
};